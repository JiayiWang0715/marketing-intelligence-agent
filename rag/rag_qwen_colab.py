def clean_response(text):
    markers = [
        "DOMINANT STRATEGY:",
        "CURRENT PATTERN:",
        "AD CONCEPT"
    ]

    # if main title appears twice, keep the first only
    for marker in markers:
        first = text.find(marker)
        if first != -1:
            second = text.find(marker, first + len(marker))
            if second != -1:
                text = text[:second].strip()

    return text.strip()

