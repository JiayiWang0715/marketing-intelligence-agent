def get_reference_ads(industry):
    docs = retrieve_docs(f"{industry} advertising strategy", top_k=5)

    unique_docs = []
    seen_prefix = set()

    for d in docs:
        key = d[:180].strip()
        if key not in seen_prefix:
            seen_prefix.add(key)
            unique_docs.append(d)

        if len(unique_docs) == 2:
            break

    return "\n\n---\n\n".join(unique_docs)

